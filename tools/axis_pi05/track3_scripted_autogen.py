def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--run", action="store_true")
    parser.add_argument("--repair-assets", action="store_true")
    parser.add_argument("--finalize-summary", action="store_true")
    parser.add_argument("--replay-worker", nargs=2, metavar=("ASSET_DIR", "RUN_INDEX"))
    args = parser.parse_args()
    if args.self_test:
        print(json.dumps(self_test(), ensure_ascii=False, sort_keys=True))
        return 0
    if args.repair_assets:
        print(json.dumps({"status": "passed", "repaired_metadata_files": repair_asset_metadata()}, ensure_ascii=False))
        return 0
    if args.finalize_summary:
        print(json.dumps(finalize_existing_summary(), ensure_ascii=False))
        return 0
    if args.replay_worker:
        recorder.configure_public_libero()
        print(json.dumps(replay_worker(Path(args.replay_worker[0]), int(args.replay_worker[1])), ensure_ascii=False, sort_keys=True))
        return 0
    if args.run:
        if os.environ.get("CUDA_VISIBLE_DEVICES") not in {"3", None}:
            raise SystemExit("S4/S5 requires CUDA_VISIBLE_DEVICES=3")
        print(json.dumps(run_all(), ensure_ascii=False, indent=2))
        return 0
    parser.error("use --self-test, --run, or --replay-worker")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
