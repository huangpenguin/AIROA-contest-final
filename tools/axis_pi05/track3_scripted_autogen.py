#!/usr/bin/env python3
"""Bounded, scripted S4/S5 executor for the three public Track 3 canaries.

The executor is intentionally narrower than the retained human teleop tool:
it uses only closed-loop EEF feedback and public LIBERO state/geometry, writes
only to ``track3_public_autogen``, and never has a promotion or training path.
One attempt is made per family in the fixed S5 order.  A failed family writes
its complete diagnostic asset and stops the sequence.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable

import numpy as np

from . import track3_public_teleop as recorder


ROOT = Path(__file__).resolve().parents[2]
REPORT_ROOT = ROOT / "data/reports/axis_libero_30k/track3_public_autogen"
S3_SUMMARY = REPORT_ROOT / "s3_reverse_adapter.json"
P1_ROOT = ROOT / "data/reports/axis_libero_30k/track3_public_terminal_recovery"
P1_SUMMARY = P1_ROOT / "p1_restore_canary_summary.json"
PENDING_ROOT = REPORT_ROOT / "pending_autogen"
DIAGNOSTIC_ROOT = REPORT_ROOT / "diagnostics"
S5_SUMMARY = REPORT_ROOT / "s5_canary_summary.json"
TASK_ORDER = ((10, "support_remove"), (20, "containment_remove"), (19, "articulation_close"))
MAX_CANARIES = 3
VIDEO_FPS = 20.0
POSITION_OUTPUT_RANGE = 0.05
REPLAY_RUNS = 3


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def atomic_bytes(path: Path, value: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + ".partial")
    with partial.open("wb") as handle:
        handle.write(value)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(partial, path)


def write_json(path: Path, value: Any) -> None:
    atomic_bytes(path, (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8"))


def save_npy(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + ".partial")
    with partial.open("wb") as handle:
        np.save(handle, np.asarray(value))
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(partial, path)


def save_npz(path: Path, arrays: dict[str, Any]) -> dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + ".partial")
    with partial.open("wb") as handle:
        np.savez_compressed(handle, **{key: np.asarray(value) for key, value in arrays.items()})
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(partial, path)
    return {"path": str(path), "sha256": sha256_file(path), "keys": sorted(arrays)}


def parse_atom(value: str) -> tuple[str, tuple[str, ...]]:
    match = re.fullmatch(r"\((\w+)\s+([^()]+)\)", str(value).strip())
    if not match:
        raise ValueError(f"unsupported predicate: {value!r}")
    return match.group(1), tuple(match.group(2).split())


def gpu_guard() -> dict[str, Any]:
    return recorder.gpu3_guard(max_used_mib=1024)


def canary_dirs(root: Path) -> list[Path]:
    return sorted(item for item in root.iterdir() if item.is_dir()) if root.is_dir() else []


def validate_preflight() -> tuple[dict[str, Any], dict[int, Path]]:
    if not S3_SUMMARY.is_file() or not P1_SUMMARY.is_file():
        raise RuntimeError("S3 adapter summary and P1 restore summary are required")
    summary = json.loads(S3_SUMMARY.read_text(encoding="utf-8"))
    if summary.get("status") != "s3_reverse_semantic_adapter_passed" or summary.get("spec_count") != 3:
        raise RuntimeError("S3 reverse adapter is not passed")
    if summary.get("official_track3_claim") or summary.get("denylist_overlap_count"):
        raise RuntimeError("S3 provenance or denylist gate failed")
    pending = canary_dirs(PENDING_ROOT)
    if len(pending) >= MAX_CANARIES:
        raise RuntimeError(f"autogenerated canary limit already reached: {len(pending)}")
    # Existing accepted material is checked, never modified or promoted.
    accepted = canary_dirs(REPORT_ROOT / "accepted")
    if accepted:
        raise RuntimeError("autogen accepted directory is non-empty; fail closed")
    p1 = json.loads(P1_SUMMARY.read_text(encoding="utf-8"))
    snapshots: dict[int, Path] = {}
    for task_index, family in TASK_ORDER:
        specs = [row for row in summary["specs"] if int(row["task_index"]) == task_index]
        if len(specs) != 1 or specs[0].get("operator_family") != family or specs[0].get("denylist_overlap"):
            raise RuntimeError(f"invalid S3 spec for task {task_index}")
        snap = P1_ROOT / "snapshots" / f"task_{task_index:02d}" / "attempt_1" / "terminal_state.npy"
        row = next((row for row in p1["attempt_results"] if int(row.get("task_index", -1)) == task_index and row.get("attempt") == 1), None)
        if row is None or not snap.is_file() or sha256_file(snap) != row.get("terminal_state_sha256"):
            raise RuntimeError(f"P1 full-state snapshot gate failed for task {task_index}")
        snapshots[task_index] = snap
    guard = gpu_guard()
    if guard.get("status") != "passed":
        raise RuntimeError(f"GPU3 preflight blocked: {guard}")
    return summary, snapshots


def load_public_predicates(spec: dict[str, Any]) -> dict[str, Any]:
    initial = [parse_atom(item) for item in spec["reverse_initial_predicates"]]
    goal = [parse_atom(item) for item in spec["reverse_goal_predicates"]]
    family = str(spec["operator_family"])
    if family == "support_remove":
        goal_on = next((args for name, args in goal if name == "On" and len(args) == 2), None)
        if goal_on is None:
            raise ValueError("support canary has no On goal")
        object_name, target_region = goal_on
        return {"object": object_name, "target_region": target_region}
    if family == "containment_remove":
        in_atom = next((args for name, args in initial if name == "In" and len(args) == 2), None)
        on_atom = next((args for name, args in goal if name == "On" and len(args) == 2), None)
        if in_atom is None or on_atom is None:
            raise ValueError("containment canary has incomplete predicates")
        return {"object": in_atom[0], "container_region": in_atom[1], "target_region": on_atom[1]}
    if family == "articulation_close":
        close_atom = next((args for name, args in goal if name == "Close" and len(args) == 1), None)
        if close_atom is None:
            raise ValueError("articulation canary has no Close goal")
        return {"region": close_atom[0]}
    raise ValueError(f"unsupported family: {family}")


def site_position(env: Any, name: str) -> np.ndarray:
    try:
        site_id = env.sim.model.site_name2id(name)
    except Exception as exc:
        raise RuntimeError(f"public MuJoCo site is absent: {name}") from exc
    return np.asarray(env.sim.data.site_xpos[site_id], dtype=np.float64).copy()


def object_position(obs: dict[str, Any], name: str) -> np.ndarray:
    key = f"{name}_pos"
    if key not in obs:
        raise RuntimeError(f"public object observation is absent: {key}")
    return np.asarray(obs[key], dtype=np.float64).reshape(3).copy()


def eef_position(obs: dict[str, Any]) -> np.ndarray:
    if "robot0_eef_pos" not in obs:
        raise RuntimeError("robot0_eef_pos is absent from public observation")
    return np.asarray(obs["robot0_eef_pos"], dtype=np.float64).reshape(3).copy()


def frame_from_obs(obs: dict[str, Any], suffix: str) -> np.ndarray:
    frame = recorder._image_from_obs(obs, suffix)
    if frame is None:
        raise RuntimeError(f"required camera frame is absent: {suffix}")
    frame = np.asarray(frame)
    if frame.ndim != 3 or frame.shape[2] != 3:
        raise RuntimeError(f"invalid camera frame shape for {suffix}: {frame.shape}")
    return frame.astype(np.uint8, copy=True)


def policy_state(obs: dict[str, Any]) -> np.ndarray:
    key = "robot0_proprio-state"
    if key not in obs:
        raise RuntimeError("robot0_proprio-state is absent from public observation")
    value = np.asarray(obs[key], dtype=np.float32).reshape(-1)
    if value.size == 0 or not np.isfinite(value).all():
        raise RuntimeError("invalid public policy state")
    return value.copy()


def closed_loop_action(obs: dict[str, Any], target: np.ndarray, gripper: float) -> tuple[np.ndarray, float, bool]:
    current = eef_position(obs)
    error = np.asarray(target, dtype=np.float64).reshape(3) - current
    raw = error / POSITION_OUTPUT_RANGE
    action = np.zeros(7, dtype=np.float32)
    action[:3] = np.clip(raw, -1.0, 1.0).astype(np.float32)
    action[-1] = 1.0 if float(gripper) >= 0 else -1.0
    recorder.validate_action(action)
    return action, float(np.linalg.norm(error)), bool(np.any(np.abs(raw) >= 0.999999))


@dataclass(frozen=True)
class Stage:
    name: str
    gripper: float
    target: Callable[[dict[str, Any]], np.ndarray]
    max_steps: int
    tolerance: float = 0.014
    stable_ticks: int = 4


@dataclass
class RunBuffer:
    actions: list[np.ndarray]
    states: list[np.ndarray]
    policy_states: list[np.ndarray]
    front: list[np.ndarray]
    wrist: list[np.ndarray]
    predicate_success: list[bool]
    phase: list[str]
    contact_count: list[int]
    deadline_miss: list[bool]
    eef_error: list[float]
    action_saturated: list[bool]
    rewards: list[float]
    dones: list[bool]

    @classmethod
    def create(cls) -> "RunBuffer":
        return cls([], [], [], [], [], [], [], [], [], [], [], [], [])


def reset_controller_goal(env: Any) -> None:
    """Refresh the OSC controller after restoring a raw simulator state."""
    robot = env.env.robots[0]
    robot.controller.update()
    robot.controller.reset_goal()


def target_for_object(obs: dict[str, Any], object_name: str, z_offset: float) -> np.ndarray:
    return object_position(obs, object_name) + np.array([0.0, 0.0, z_offset], dtype=np.float64)


def target_for_region(env: Any, region_name: str, z_offset: float) -> np.ndarray:
    return site_position(env, region_name) + np.array([0.0, 0.0, z_offset], dtype=np.float64)


def build_stages(env: Any, spec: dict[str, Any], obs: dict[str, Any]) -> list[Stage]:
    details = load_public_predicates(spec)
    family = spec["operator_family"]
    if family == "support_remove":
        object_name = details["object"]
        region = details["target_region"]
        contact = object_position(obs, object_name) + np.array([0.0, 0.0, 0.025])
        return [
            Stage("approach_object", -1.0, lambda o: target_for_object(o, object_name, 0.12), 150),
            Stage("descend_object", -1.0, lambda o: target_for_object(o, object_name, 0.025), 120, 0.011),
            Stage("grasp_object", 1.0, lambda _o: contact, 35, 0.018, 1),
            Stage("lift_object", 1.0, lambda _o: contact + np.array([0.0, 0.0, 0.14]), 150),
            Stage("transport_to_target", 1.0, lambda _o: target_for_region(env, region, 0.14), 180),
            Stage("descend_to_target", 1.0, lambda _o: target_for_region(env, region, 0.055), 120, 0.012),
            Stage("release_object", -1.0, lambda _o: target_for_region(env, region, 0.055), 35, 0.02, 1),
            Stage("retreat", -1.0, lambda _o: target_for_region(env, region, 0.16), 80),
        ]
    if family == "containment_remove":
        object_name = details["object"]
        region = details["target_region"]
        contact = object_position(obs, object_name) + np.array([0.0, 0.0, 0.025])
        return [
            Stage("approach_object", -1.0, lambda o: target_for_object(o, object_name, 0.13), 170),
            Stage("descend_object", -1.0, lambda o: target_for_object(o, object_name, 0.025), 140, 0.012),
            Stage("grasp_object", 1.0, lambda _o: contact, 45, 0.02, 1),
            Stage("lift_object", 1.0, lambda _o: contact + np.array([0.0, 0.0, 0.16]), 170),
            Stage("transport_to_target", 1.0, lambda _o: target_for_region(env, region, 0.13), 220),
            Stage("descend_to_target", 1.0, lambda _o: target_for_region(env, region, 0.075), 140, 0.014),
            Stage("release_object", -1.0, lambda _o: target_for_region(env, region, 0.075), 40, 0.022, 1),
            Stage("retreat", -1.0, lambda _o: target_for_region(env, region, 0.18), 90),
        ]
    region = details["region"]
    start_site = site_position(env, region)
    close_target = start_site + np.array([0.0, -0.20, 0.0])
    return [
        Stage("approach_drawer_region", -1.0, lambda _o: start_site + np.array([0.0, -0.012, 0.012]), 180, 0.015),
        Stage("grasp_drawer_region", 1.0, lambda _o: start_site + np.array([0.0, -0.012, 0.012]), 40, 0.022, 1),
        Stage("pull_drawer_closed", 1.0, lambda _o: close_target, 280, 0.018),
        Stage("hold_closed", 1.0, lambda _o: close_target, 45, 0.025, 1),
    ]


def append_step(buffer: RunBuffer, obs: dict[str, Any], action: np.ndarray, reward: float, done: bool, phase: str, deadline: bool, error: float, saturated: bool, env: Any) -> None:
    buffer.actions.append(np.asarray(action, dtype=np.float32).copy())
    buffer.states.append(np.asarray(env.get_sim_state(), dtype=np.float64).copy())
    buffer.policy_states.append(policy_state(obs))
    buffer.front.append(frame_from_obs(obs, "agentview"))
    buffer.wrist.append(frame_from_obs(obs, "robot0_eye_in_hand"))
    buffer.predicate_success.append(bool(env.check_success()))
    buffer.phase.append(phase)
    buffer.contact_count.append(int(getattr(env.sim.data, "ncon", 0)))
    buffer.deadline_miss.append(bool(deadline))
    buffer.eef_error.append(float(error))
    buffer.action_saturated.append(bool(saturated))
    buffer.rewards.append(float(reward))
    buffer.dones.append(bool(done))


def encode_h264(path: Path, frames: list[np.ndarray]) -> dict[str, Any]:
    if not frames:
        return {"status": "no_frames"}
    first = np.asarray(frames[0], dtype=np.uint8)
    if first.ndim != 3 or first.shape[2] != 3:
        raise ValueError(f"invalid video frame: {first.shape}")
    height, width = first.shape[:2]
    payload = b"".join(np.asarray(frame, dtype=np.uint8).reshape(height, width, 3).tobytes() for frame in frames)
    partial = path.with_name(path.stem + ".partial" + path.suffix)
    command = ["ffmpeg", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{width}x{height}", "-r", str(VIDEO_FPS), "-i", "-", "-an", "-c:v", "libx264", "-preset", "ultrafast", "-crf", "20", "-pix_fmt", "yuv420p", str(partial)]
    result = subprocess.run(command, input=payload, capture_output=True, check=False)
    if result.returncode != 0 or not partial.is_file() or partial.stat().st_size == 0:
        partial.unlink(missing_ok=True)
        return {"status": "encode_failed", "stderr": result.stderr.decode(errors="replace")[-2000:]}
    os.replace(partial, path)
    return {"status": "written", "codec": "h264", "path": str(path), "sha256": sha256_file(path), "frame_count": len(frames), "width": width, "height": height}


def write_asset(directory: Path, metadata: dict[str, Any], buffer: RunBuffer, start_state: np.ndarray, end_state: np.ndarray) -> None:
    arrays = {
        "actions": buffer.actions,
        "states": buffer.states,
        "policy_states": buffer.policy_states,
        "predicate_success": buffer.predicate_success,
        "phase": np.asarray(buffer.phase, dtype="U64"),
        "contact_count": buffer.contact_count,
        "deadline_miss": buffer.deadline_miss,
        "eef_error": buffer.eef_error,
        "action_saturated": buffer.action_saturated,
        "rewards": buffer.rewards,
        "dones": buffer.dones,
    }
    trajectory = save_npz(directory / "trajectory.npz", arrays)
    save_npy(directory / "start_state.npy", start_state)
    save_npy(directory / "end_state.npy", end_state)
    videos = {"front": encode_h264(directory / "front.mp4", buffer.front), "wrist": encode_h264(directory / "wrist.mp4", buffer.wrist)}
    metadata.update({
        "frame_count": len(buffer.actions),
        "trajectory": trajectory,
        "start_state_sha256": sha256_file(directory / "start_state.npy"),
        "end_state_sha256": sha256_file(directory / "end_state.npy"),
        "end_success": bool(buffer.predicate_success[-1]) if buffer.predicate_success else False,
        "first_success_frame": next((i for i, value in enumerate(buffer.predicate_success) if value), None),
        "deadline_miss_count": int(sum(bool(value) for value in buffer.deadline_miss)),
        "action_saturation_count": int(sum(bool(value) for value in buffer.action_saturated)),
        "videos": videos,
    })
    write_json(directory / "metadata.json", metadata)


def _replace_partial_paths(value: Any, partial_dir: str, final_dir: str) -> Any:
    if isinstance(value, str):
        return value.replace(partial_dir, final_dir)
    if isinstance(value, list):
        return [_replace_partial_paths(item, partial_dir, final_dir) for item in value]
    if isinstance(value, dict):
        return {key: _replace_partial_paths(item, partial_dir, final_dir) for key, item in value.items()}
    return value


def repair_asset_metadata(root: Path = REPORT_ROOT) -> int:
    """Repair only stale atomic-temp paths left in already-written diagnostics."""
    repaired = 0
    for metadata_path in sorted(root.glob("**/metadata.json")):
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        final_dir = str(metadata_path.parent.resolve())
        changed = _replace_partial_paths(metadata, str(metadata_path.parent.parent / ("." + metadata_path.parent.name + ".partial")), final_dir)
        if changed != metadata:
            write_json(metadata_path, changed)
            repaired += 1
    return repaired


def finalize_existing_summary() -> dict[str, Any]:
    """Materialize the plan-named S5 summary without rerunning a canary."""
    source = REPORT_ROOT / "s5_autogen_summary.json"
    if not source.is_file():
        raise FileNotFoundError(source)
    value = json.loads(source.read_text(encoding="utf-8"))
    for index, canary in enumerate(value.get("canaries", [])):
        asset_dir = Path(str(canary.get("asset_dir", "")))
        metadata_path = asset_dir / "metadata.json"
        if metadata_path.is_file():
            value["canaries"][index] = json.loads(metadata_path.read_text(encoding="utf-8"))
    write_json(S5_SUMMARY, value)
    write_json(source, value)
    return {"status": "passed", "summary": str(S5_SUMMARY), "source": str(source), "canary_rerun": False}


def atomic_asset(parent: Path, name: str, writer: Callable[[Path], None]) -> Path:
    parent.mkdir(parents=True, exist_ok=True)
    partial = parent / f".{name}.partial"
    if partial.exists():
        shutil.rmtree(partial)
    partial.mkdir()
    try:
        writer(partial)
        target = parent / name
        if target.exists():
            raise FileExistsError(target)
        os.replace(partial, target)
        return target
    except Exception:
        shutil.rmtree(partial, ignore_errors=True)
        raise


def run_one(spec: dict[str, Any], snapshot: Path, run_id: str) -> dict[str, Any]:
    from libero.libero.envs import OffScreenRenderEnv

    task_index = int(spec["task_index"])
    config_dir = recorder.configure_public_libero()
    env = OffScreenRenderEnv(
        bddl_file_name=spec["reverse_bddl_path"],
        control_freq=20,
        use_camera_obs=True,
        camera_names=["agentview", "robot0_eye_in_hand"],
        camera_heights=128,
        camera_widths=128,
        render_gpu_device_id=0,
    )
    buffer = RunBuffer.create()
    start_state = np.asarray(np.load(snapshot), dtype=np.float64).copy()
    metadata: dict[str, Any] = {
        "schema_version": "track3_public_autogen_canary_v1",
        "canary_id": run_id,
        "task_index": task_index,
        "operator_family": spec["operator_family"],
        "identity": "generator_reference_only",
        "source": "public_LIBERO_BDDL_plus_P1_full_state_start",
        "generator": "track3_scripted_autogen_closed_loop_osc_pose",
        "generator_provenance": spec["generator_provenance"],
        "reverse_bddl_path": spec["reverse_bddl_path"],
        "reverse_bddl_sha256": spec["reverse_bddl_sha256"],
        "reverse_instruction": spec["reverse_instruction"],
        "official_track3_claim": False,
        "training_eligible": False,
        "human_operation": False,
        "control_freq_hz": VIDEO_FPS,
        "action_contract": "7D OSC_POSE delta action; translation/rotation normalized; gripper exactly -1 or +1",
        "state_contract": "complete simulator state after every action plus exact restored start_state",
        "status": "running",
        "created_at_utc": utc_now(),
        "gpu_policy": {"physical_gpu": 3, "visible_device": "3", "mujoco_render_gpu_device_id": 0},
        "p1_start_state_sha256": sha256_file(snapshot),
        "config_dir": str(config_dir),
    }
    status = "failed"
    failure_reason: str | None = None
    stage_results: list[dict[str, Any]] = []
    try:
        env.reset()
        obs = env.set_init_state(start_state)
        reset_controller_goal(env)
        if bool(env.check_success()):
            raise RuntimeError("reverse goal already true at start state")
        stages = build_stages(env, spec, obs)
        for stage in stages:
            stable = 0
            reached = False
            stage_start = len(buffer.actions)
            last_error = float("inf")
            for local_step in range(stage.max_steps):
                target = np.asarray(stage.target(obs), dtype=np.float64).reshape(3)
                action, error, saturated = closed_loop_action(obs, target, stage.gripper)
                tick = time.monotonic()
                obs, reward, done, _info = env.step(action)
                elapsed = time.monotonic() - tick
                last_error = error
                append_step(buffer, obs, action, reward, done, stage.name, elapsed > (1.0 / VIDEO_FPS + 0.005), error, saturated, env)
                if buffer.predicate_success[-1]:
                    reached = True
                    break
                if error <= stage.tolerance:
                    stable += 1
                else:
                    stable = 0
                if stable >= stage.stable_ticks:
                    reached = True
                    break
                if done:
                    break
            stage_results.append({"stage": stage.name, "frames": len(buffer.actions) - stage_start, "reached": reached, "last_eef_error": last_error, "max_steps": stage.max_steps})
            if not reached:
                failure_reason = f"stage_timeout:{stage.name}"
                break
        if failure_reason is None and bool(env.check_success()):
            status = "generated_predicate_pass"
        elif failure_reason is None:
            failure_reason = "final_predicate_false"
    except Exception as exc:
        failure_reason = f"{type(exc).__name__}: {exc}"
    finally:
        try:
            end_state = np.asarray(env.get_sim_state(), dtype=np.float64).copy()
        except Exception:
            end_state = start_state.copy()
        try:
            env.close()
        except Exception:
            pass
    metadata.update({"status": status, "failure_reason": failure_reason, "stage_results": stage_results, "end_success": bool(buffer.predicate_success[-1]) if buffer.predicate_success else False})
    bucket = PENDING_ROOT if status == "generated_predicate_pass" else DIAGNOSTIC_ROOT
    name = run_id
    target = atomic_asset(bucket, name, lambda directory: write_asset(directory, metadata, buffer, start_state, end_state))
    metadata = _replace_partial_paths(metadata, str(bucket / f".{name}.partial"), str(target))
    metadata["asset_dir"] = str(target)
    # metadata.json was written inside the atomic directory; update it once
    # more with final paths without exposing a partially written directory.
    write_json(target / "metadata.json", metadata)
    return metadata


def replay_worker(asset_dir: Path, run_index: int) -> dict[str, Any]:
    """Fresh-process worker used only for S5 validation; it never writes accepted."""
    from libero.libero.envs import OffScreenRenderEnv

    metadata = json.loads((asset_dir / "metadata.json").read_text(encoding="utf-8"))
    spec = next(row for row in json.loads(S3_SUMMARY.read_text(encoding="utf-8"))["specs"] if int(row["task_index"]) == int(metadata["task_index"]))
    actions = np.asarray(np.load(asset_dir / "trajectory.npz", allow_pickle=False)["actions"], dtype=np.float32)
    start = np.asarray(np.load(asset_dir / "start_state.npy"), dtype=np.float64)
    env = OffScreenRenderEnv(bddl_file_name=spec["reverse_bddl_path"], control_freq=20, use_camera_obs=False, render_gpu_device_id=0)
    try:
        env.reset(); env.set_init_state(start); reset_controller_goal(env)
        start_success = bool(env.check_success())
        for action in actions:
            recorder.validate_action(action)
            env.step(action)
        end_success = bool(env.check_success())
        return {"run_index": run_index, "status": "passed" if not start_success and end_success else "failed_predicate", "frame_count": len(actions), "start_success": start_success, "end_success": end_success, "gpu_policy": "physical_gpu3_only"}
    except Exception as exc:
        return {"run_index": run_index, "status": "failed_exception", "error": f"{type(exc).__name__}: {exc}"}
    finally:
        env.close()


def fresh_replay(asset_dir: Path) -> dict[str, Any]:
    results: list[dict[str, Any]] = []
    for run_index in range(1, REPLAY_RUNS + 1):
        child_env = os.environ.copy()
        child_env.update({"CUDA_VISIBLE_DEVICES": "3", "MUJOCO_EGL_DEVICE_ID": "3", "MUJOCO_GL": "egl", "PYTHONPATH": f"{ROOT / 'LIBERO'}:{ROOT}"})
        command = [sys.executable, "-m", "tools.axis_pi05.track3_scripted_autogen", "--replay-worker", str(asset_dir), str(run_index)]
        completed = subprocess.run(command, env=child_env, capture_output=True, text=True, check=False)
        lines = [line for line in completed.stdout.splitlines() if line.strip()]
        try:
            result = json.loads(lines[-1]) if lines else {"status": "worker_no_output", "stderr": completed.stderr[-2000:]}
        except json.JSONDecodeError:
            result = {"status": "worker_output_invalid", "stdout": completed.stdout[-2000:], "stderr": completed.stderr[-2000:]}
        result["worker_returncode"] = completed.returncode
        results.append(result)
        if result.get("status") != "passed":
            break
    passed = sum(item.get("status") == "passed" for item in results)
    result = {"schema_version": "track3_public_autogen_replay_v1", "status": "replay_3_of_3_passed" if passed == REPLAY_RUNS else "replay_failed", "required_runs": REPLAY_RUNS, "passed_runs": passed, "runs": results, "created_at_utc": utc_now(), "accepted_promotion": False}
    write_json(asset_dir / "replay_summary.json", result)
    metadata = json.loads((asset_dir / "metadata.json").read_text(encoding="utf-8"))
    metadata["replay"] = f"{passed}/{REPLAY_RUNS}_passed"
    metadata["status"] = "pending_autogen" if passed == REPLAY_RUNS else "replay_failed_pending_diagnostic_review"
    write_json(asset_dir / "metadata.json", metadata)
    return result


def run_all() -> dict[str, Any]:
    summary, snapshots = validate_preflight()
    result: dict[str, Any] = {
        "schema_version": "track3_public_autogen_s5_v1",
        "status": "running",
        "plan_scope": "S4-S5_only",
        "task_order": [{"task_index": task, "operator_family": family} for task, family in TASK_ORDER],
        "max_pending_autogen_canaries": MAX_CANARIES,
        "human_operation": False,
        "training_started": False,
        "official_gpu_used": False,
        "fast_or_zip_used": False,
        "s3_adapter_sha256": sha256_file(S3_SUMMARY),
        "canaries": [],
        "created_at_utc": utc_now(),
    }
    for task_index, family in TASK_ORDER:
        spec = next(row for row in summary["specs"] if int(row["task_index"]) == task_index)
        run_id = f"{family}_task_{task_index:02d}"
        canary = run_one(spec, snapshots[task_index], run_id)
        if canary.get("status") == "generated_predicate_pass":
            asset_dir = Path(canary["asset_dir"])
            replay = fresh_replay(asset_dir)
            canary["replay"] = replay
            if replay.get("status") == "replay_3_of_3_passed":
                canary["status"] = "pending_autogen"
                write_json(asset_dir / "metadata.json", canary)
            else:
                canary["status"] = "replay_failed_pending_diagnostic_review"
            result["canaries"].append(canary)
            if canary["status"] != "pending_autogen":
                result["status"] = "track3_autogen_replay_gap_pending_review"
                break
        else:
            result["canaries"].append(canary)
            result["status"] = "track3_scripted_executor_failed"
            break
    else:
        result["status"] = "track3_autogen_three_family_canary_pending_human_video_review"
    result["gpu3_after"] = gpu_guard()
    result["pending_autogen_count"] = len(canary_dirs(PENDING_ROOT))
    if result["gpu3_after"].get("status") != "passed":
        result["status"] = "track3_autogen_gpu3_postflight_gap_pending_review"
    write_json(S5_SUMMARY, result)
    # Keep the earlier descriptive filename as a compatibility pointer for
    # local readers; the plan's canonical artifact is s5_canary_summary.json.
    write_json(REPORT_ROOT / "s5_autogen_summary.json", result)
    return result


def self_test() -> dict[str, Any]:
    action, error, saturated = closed_loop_action({"robot0_eef_pos": np.zeros(3)}, np.array([0.025, -0.1, 0.05]), -1.0)
    assert action.shape == (7,) and action[-1] == -1.0 and error > 0 and saturated is True
